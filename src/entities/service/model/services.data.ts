export type ServiceIncludedGroup = {
  number: string
  title: string
  text: string
  items: readonly string[]
}

export type ServiceIncluded = {
  label: string
  titleMain: string
  titleAccent: string
  lead: string
  groups: readonly ServiceIncludedGroup[]
  fit: {
    label: string
    title: string
    text: string
    points: readonly string[]
  }
  note: string
}

export type ServiceStoryIndividual = {
  eyebrow: string
  title: string
  lead: string
  hero: {
    overline: string
    title: string
    text: string
    metrics: ReadonlyArray<{ value: string; label: string }>
  }
  highlights: ReadonlyArray<{
    label: string
    title: string
    text: string
  }>
  steps: ReadonlyArray<{
    label: string
    title: string
    text: string
  }>
}

export type ServiceStoryPackage = {
  eyebrow: string
  title: string
  lead: string
  summary: {
    overline: string
    title: string
    text: string
    bullets: readonly string[]
  }
  steps: ReadonlyArray<{
    number: string
    title: string
    text: string
    meta: string
  }>
}

type ServiceHero = {
  eyebrow: string
  titleLine: string
  titleAccent: string
  lead: string
  stats: ReadonlyArray<{
    label: string
    value: string
  }>
  aside: {
    eyebrow: string
    title: string
    text: string
  }
}

type ServiceBase = {
  slug: string
  number: string
  title: string
  shortText: string
  text: string
  tags: readonly string[]
  image: string
  imageWidth: number
  imageHeight: number
  lead: string
  hero: ServiceHero
  bullets: readonly string[]
  metrics: ReadonlyArray<{
    value: string
    label: string
  }>
  price: string
  duration: string
  ctaLabel: string
  included: ServiceIncluded
  seo: {
    title: string
    description: string
    keywords: string
  }
}

export type ServiceIndividual = ServiceBase & {
  id: 'individual'
  story: ServiceStoryIndividual
}

export type ServicePackage = ServiceBase & {
  id: 'package'
  story: ServiceStoryPackage
}

